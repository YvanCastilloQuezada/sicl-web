"use strict";
const assert=require("node:assert/strict");
const {appendEvent,deriveMemory}=require("./arki-living-memory.cjs");
const base={id:"AUDIT_001",type:"AUDIT_RECEIVED",occurredAt:"2026-10-10T20:00:00Z",source:"Qwen audit report",summary:"Historical review with unresolved provenance",evidenceState:"DECLARED",subject:"E2E-001",sha:null};
let a=appendEvent([],base);
assert.equal(a.status,"APPENDED_LOCAL");
assert.equal(a.log.length,1);
assert.equal(a.canonicalMutation,false);
assert.equal(appendEvent(a.log,base).status,"REJECTED_DUPLICATE");
assert.equal(appendEvent(a.log,{...base,id:"AUDIT_002",type:"FAKE"}).status,"REJECTED_INVALID");
const next={...base,id:"TEST_001",type:"TEST_OBSERVED",occurredAt:"2026-10-10T21:00:00Z",summary:"Synthetic test result observed in local environment",evidenceState:"VERIFIED",sha:"a".repeat(40)};
const b=appendEvent(a.log,next);
assert.equal(b.log.length,2);
assert.equal(a.log.length,1);
assert.equal(b.log[1].previousHash.length,64);
const memory=deriveMemory(b.log);
assert.equal(memory.eventCount,2);
assert.deepEqual(memory.unverified,["AUDIT_001"]);
assert.equal(memory.promotion,"BLOCKED");
assert.equal(memory.execution,"BLOCKED");
assert.equal(memory.criticalPath,"UNKNOWN");
assert.equal(memory.canonicalMutation,false);
console.log("ARKI_LIVING_MEMORY_TESTS=PASS");
