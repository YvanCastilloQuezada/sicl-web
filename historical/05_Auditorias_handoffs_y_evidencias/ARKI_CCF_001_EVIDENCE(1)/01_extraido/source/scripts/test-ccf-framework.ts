import { strict as assert } from "node:assert";
import { readFile } from "node:fs/promises";
const root = "/home/ubuntu/generador-familias";
const contract = await readFile(`${root}/shared/arkiCommandCenterFramework.ts`, "utf8");
const shell = await readFile(`${root}/client/src/components/AreaCommandCenterShell.tsx`, "utf8");
const page = await readFile(`${root}/client/src/pages/AutopilotCommandCenter.tsx`, "utf8");
const areas = JSON.parse(await readFile(`${root}/client/public/__autopilot__/areas.json`, "utf8")) as Array<{ areaId: string; status: string; maturity: string; source: string[]; health: string }>;
const events = JSON.parse(await readFile(`${root}/client/public/__autopilot__/events.json`, "utf8")) as Array<{ eventId: string; timestamp: string; areaId: string; severity: string; status: string; evidenceRefs: string[] }>;
const graph = JSON.parse(await readFile(`${root}/client/public/__autopilot__/dependencies.json`, "utf8`".replace("utf8`", "utf8"))) as { nodes: unknown[]; edges: unknown[] };
for (const token of ["CcfAreaDefinition", "CcfAreaEvent", "CcfDependency", "CcfAction", "CcfObservation", "ccfEventFromLegacy", "isTruthfulMaturity"]) assert(contract.includes(token), `missing CCF contract token ${token}`);
for (const token of ["AREA COMMAND CENTER", "OBJECTIVE", "CURRENT ACTION", "data-area-id"]) assert(shell.includes(token), `missing shared shell token ${token}`);
for (const token of ["PROJECT COMMAND VIEW", "SYSTEM COMMAND VIEW", "HUMAN AUTHORITY CENTER", "WHY BLOCKED / LIMITED?", "DIRECTOR", "LIVE", "FORENSIC", "PO DIRECTIVE CONSOLE"]) assert(page.includes(token), `missing UI token ${token}`);
assert(areas.length >= 20, "registry must include actual and candidate areas");
assert(areas.some(area => area.areaId === "bim" && area.status !== "NOT_IMPLEMENTED"));
assert(areas.some(area => area.status === "NOT_IMPLEMENTED"));
assert(areas.some(area => area.maturity === "DOCUMENTED" || area.maturity === "UNKNOWN"));
assert(events.length >= 29 && events.every(event => event.eventId && event.areaId && event.evidenceRefs));
assert(events.every((event, index) => index === 0 || event.timestamp >= events[index - 1].timestamp), "out-of-order event accepted");
assert(graph.nodes.length >= 6 && graph.edges.length >= 5);
assert(!page.includes("chain of thought"));
assert(page.includes("No silent execution") || page.includes("no silent execution"));
// Adversarial state checks: unknown/unsupported data remains visible and cannot become implementation claims.
const unknownAreas = areas.filter(area => area.status === "UNKNOWN" || area.health === "UNKNOWN");
assert(unknownAreas.length > 0, "UNKNOWN state must remain represented");
assert(events.some(event => event.status === "FAIL" || event.severity === "ERROR"), "failure must remain observable");
